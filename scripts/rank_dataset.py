def aggregate_rankings_fallback(rankings_list, num_items):
    """
    Mathematical fallback (Borda Count) to aggregate rankings if LLM fails to output valid JSON.
    """
    scores = {f"R{i}": [] for i in range(1, num_items + 1)}
    for r in rankings_list:
        for pos, item in enumerate(r):
            if item in scores:
                scores[item].append(pos)
                
    mean_scores = {}
    for item, positions in scores.items():
        if positions:
            mean_scores[item] = sum(positions) / len(positions)
        else:
            mean_scores[item] = num_items / 2.0  # middle fallback
            
    sorted_items = sorted(mean_scores.keys(), key=lambda x: mean_scores[x])
    return sorted_items

def run_single_ranker(product_name, question, review_items, agent_idx):
    """
    Run one of the 5 parallel Ranker Agents.
    """
    review_lines = "\n".join([f"- {r_id}: \"{text}\"" for r_id, text in review_items])
    user_prompt = f"""Product Name: {product_name}
Question: {question}

Reviews to rank:
{review_lines}"""
    
    try:
        response = call_llm(SYSTEM_RANKER, [{"role": "user", "content": user_prompt}], max_tokens=16000, temperature=0.7)
        cleaned = clean_json(response)
        parsed = json.loads(cleaned)
        ranking = parsed.get("ranking", [])
        # Basic validation
        expected_ids = {r_id for r_id, _ in review_items}
        if set(ranking) == expected_ids:
            return parsed
        else:
            print(f"    Ranker {agent_idx} returned invalid ID set. Raw: {ranking}")
    except Exception as e:
        print(f"    Error running Ranker {agent_idx}: {e}")
    return None

def process_product_ranking(product_name, question, reviews):
    """
    Consensus Ranking Pipeline for a single product:
    1. Runs 5 parallel ranker agents.
    2. Runs 1 consensus judge agent.
    """
    num_reviews = len(reviews)
    review_items = [(f"R{i+1}", reviews[i]) for i in range(num_reviews)]
    
    # 1. Run 5 Rankers in parallel
    print(f"  Starting 5 Rankers for '{product_name[:40]}...'")
    rankers_results = []
    
    with ThreadPoolExecutor(max_workers=5) as executor:
        futures = {executor.submit(run_single_ranker, product_name, question, review_items, i+1): i for i in range(5)}
        for future in as_completed(futures):
            res = future.result()
            if res:
                rankers_results.append(res)
                
    print(f"    Completed Rankers: {len(rankers_results)}/5 succeeded.")
    
    # Extract only the valid rankings
    valid_rankings = [res["ranking"] for res in rankers_results if "ranking" in res]
    
    # 2. Run Consensus Judge
    print("  Running Consensus Judge...")
    annotators_text = ""
    for idx, res in enumerate(rankers_results):
        annotators_text += f"\n- Annotator {idx+1}:\n  Reasoning: {res.get('reasoning')}\n  Ranking: {res.get('ranking')}\n"
        
    review_lines = "\n".join([f"- {r_id}: \"{text}\"" for r_id, text in review_items])
    judge_prompt = f"""Product Name: {product_name}
Question: {question}

Reviews:
{review_lines}

Rankings from 5 Annotators:
{annotators_text}"""
    
    consensus_ranking = None
    try:
        response = call_llm(SYSTEM_CONSENSUS_JUDGE, [{"role": "user", "content": judge_prompt}], max_tokens=16000, temperature=0.2)
        cleaned = clean_json(response)
        parsed = json.loads(cleaned)
        consensus_ranking = parsed.get("consensus_ranking", [])
    except Exception as e:
        print(f"    Consensus Judge call failed or returned invalid JSON: {e}")
        
    # Validation & Fallback
    expected_ids = {r_id for r_id, _ in review_items}
    if not consensus_ranking or set(consensus_ranking) != expected_ids:
        print("    WARNING: Consensus ranking is invalid. Applying mathematical Borda-count aggregation fallback.")
        if valid_rankings:
            consensus_ranking = aggregate_rankings_fallback(valid_rankings, num_reviews)
        else:
            # Hard fallback: keep original order
            consensus_ranking = [f"R{i+1}" for i in range(num_reviews)]
            
    print(f"    Final consensus ranking: {consensus_ranking}")
    
    # Map consensus ranking back to list of ranks (1-based index of item in sorted list)
    ranks = [num_reviews] * num_reviews  # default to lowest rank
    for rank_idx, r_id in enumerate(consensus_ranking):
        try:
            rev_idx = int(r_id[1:]) - 1
            if 0 <= rev_idx < num_reviews:
                ranks[rev_idx] = rank_idx + 1
        except Exception:
            pass
            
    return ranks

