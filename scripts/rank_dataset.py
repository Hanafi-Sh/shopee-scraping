def clean_json(text):
    text = text.strip()
    if text.startswith("```json"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
    return text.strip()

def call_llm(system_prompt, messages, max_tokens=16000, temperature=0.7):
    """
    Call the Anthropic-compatible API endpoint with retries and exponential backoff.
    Sets max_tokens to 16000 for complex reasoning.
    """
    payload = {
        "model": "claude-3-5-sonnet-20241022",
        "max_tokens": max_tokens,
        "system": system_prompt,
        "messages": messages,
        "temperature": temperature
    }
    
    max_retries = 20
    for attempt in range(max_retries):
        try:
            response = requests.post(API_ENDPOINT, json=payload, headers=headers, timeout=90)
            if response.status_code == 200:
                resp_json = response.json()
                content = resp_json.get("content", [])
                if content and len(content) > 0:
                    return content[0].get("text", "")
                raise ValueError("Empty content in response")
            elif response.status_code in [429, 503]:
                sleep_time = 30
                print(f"API Cooldown/Replenishing (503/429) detected. Sleeping {sleep_time}s before retry (Attempt {attempt+1}/{max_retries})...")
                time.sleep(sleep_time)
            else:
                backoff = min(2 ** attempt, 30)
                print(f"API Error {response.status_code}: {response.text[:200]}. Retrying in {backoff}s...")
                time.sleep(backoff)
        except Exception as e:
            backoff = min(2 ** attempt, 30)
            print(f"Connection error: {e}. Retrying in {backoff}s...")
            time.sleep(backoff)
    
    raise RuntimeError("API failed after maximum retries.")

